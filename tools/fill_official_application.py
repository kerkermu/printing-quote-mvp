def cell(row, index):
    return row.cells[index]


def format_run(run, font_size: float = 10.0) -> None:
    run.font.name = "標楷體"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "標楷體")
    run.font.size = Pt(font_size)


def format_paragraph(paragraph, font_size: float = 10.0) -> None:
    for run in paragraph.runs:
        format_run(run, font_size)


def set_cell_text(target_cell, value: str, font_size: float = 10.0) -> None:
    target_cell.text = value or ""
    for paragraph in target_cell.paragraphs:
        format_paragraph(paragraph, font_size)


def replace_text_preserving_runs(doc: Document, replacements: dict[str, str]) -> None:
    for paragraph in doc.paragraphs:
        replace_in_paragraph(paragraph, replacements)
    for table in doc.tables:
        for row in table.rows:
            for target_cell in row.cells:
                for paragraph in target_cell.paragraphs:
                    replace_in_paragraph(paragraph, replacements)


def replace_in_paragraph(paragraph, replacements: dict[str, str]) -> None:
    if not paragraph.runs:
        return
    text = "".join(run.text for run in paragraph.runs)
    new_text = text
    for old, new in replacements.items():
        new_text = new_text.replace(old, new)
    if new_text == text:
        return
    paragraph.runs[0].text = new_text
    format_run(paragraph.runs[0])
    for run in paragraph.runs[1:]:
        run.text = ""


def mark_checked_boxes(doc: Document, selected_item_ids: list[str], label_map: dict[str, str]) -> None:
    selected_labels = {label_map[item_id] for item_id in selected_item_ids if item_id in label_map}
    replacements = {}
    for label in selected_labels:
        replacements[f"□ {label}"] = f"■ {label}"
        replacements[f"□{label}"] = f"■{label}"
    replace_text_preserving_runs(doc, replacements)


def fill_common_fields(doc: Document, data: dict) -> None:
    table = doc.tables[0]
    customer = data.get("customer", {})
    sample = data.get("sample", {})
    application_date = data.get("application_date") or date.today().isoformat()

    set_cell_text(cell(table.rows[0], 2), customer.get("company_name", ""))
    set_cell_text(cell(table.rows[0], 11), application_date)
    set_cell_text(cell(table.rows[1], 2), customer.get("invoice_address") or customer.get("address", ""))
    set_cell_text(cell(table.rows[1], 11), customer.get("tax_id", ""))
    set_cell_text(cell(table.rows[2], 2), customer.get("address", ""))
    set_cell_text(cell(table.rows[2], 11), customer.get("contact_name", ""))
    set_cell_text(cell(table.rows[3], 2), customer.get("email", ""))
    set_cell_text(cell(table.rows[3], 11), customer.get("job_title", ""))
    set_cell_text(cell(table.rows[4], 2), customer.get("phone", ""))
    set_cell_text(cell(table.rows[4], 5), customer.get("fax", ""))
    set_cell_text(cell(table.rows[4], 11), customer.get("mobile", ""))

    sample_text = (
        f"測試件名稱：{sample.get('name', '')}　"
        f"測試件數量：{sample.get('quantity', '')}\n"
        f"測試件狀態描述：{sample.get('description', '')}"
    )
    set_cell_text(cell(table.rows[5], 1), sample_text, font_size=9.5)

    sample_return = sample.get("sample_return")
    report_delivery = sample.get("report_delivery")
    if sample_return:
        return_text = (
            f"剩餘測試件處理方式：{'■' if sample_return == '取回' else '□'}取回 "
            f"{'■' if sample_return == '不取回' else '□'}不取回"
        )
        set_cell_text(cell(table.rows[6], 1), return_text)
    if report_delivery:
        delivery_text = (
            f"正式紙本報告取件方式：{'■' if report_delivery == '自取' else '□'}自取 "
            f"{'■' if report_delivery == '郵寄' else '□'}郵寄"
        )
        set_cell_text(cell(table.rows[6], 7), delivery_text)

    case_type = sample.get("case_type", "一般件")
    replacements = {
        "□ 一般件": f"{'■' if case_type == '一般件' else '□'} 一般件",
        "□ 急件": f"{'■' if case_type == '急件' else '□'} 急件",
        "□ 特急件": f"{'■' if case_type == '特急件' else '□'} 特急件",
    }
    attachments = set(sample.get("attachments", []))
    if "工廠登記證影本一份" in attachments:
        replacements["□工廠登記證影本一份"] = "■工廠登記證影本一份"
    if "公司執照影本一份" in attachments:
        replacements["□公司執照影本一份"] = "■公司執照影本一份"
    if "其他" in attachments or sample.get("attachment_other"):
        replacements["□其他_______"] = f"■其他 {sample.get('attachment_other', '')}"
        replacements["□其他________"] = f"■其他 {sample.get('attachment_other', '')}"
    replace_text_preserving_runs(doc, replacements)

    report_language = sample.get("report_language", "中文")
    replacements = {}
    if "中文" in report_language:
        replacements["□ 中文報告     份"] = "■ 中文報告  1  份"
    if "英文" in report_language:
        replacements["□ 英文報告_____份"] = "■ 英文報告__1__份"
    replace_text_preserving_runs(doc, replacements)


def fill_note_total(doc: Document, total: int | str | None) -> None:
    # The official application form keeps this amount blank for internal use.
    return


def choose_template(data: dict, paper_template: Path, ink_template: Path) -> tuple[Path, dict[str, str]]:
    service_type = data.get("service_type")
    if service_type == "paper":
        return paper_template, PAPER_ITEM_LABELS
    if service_type == "ink":
        return ink_template, INK_ITEM_LABELS

    selected = data.get("selected_item_ids", [])
    if selected and all(item_id.startswith("paper-") for item_id in selected):
        return paper_template, PAPER_ITEM_LABELS
    return ink_template, INK_ITEM_LABELS


def fill_application(data: dict, paper_template: Path, ink_template: Path, output: Path) -> Path:
    template, label_map = choose_template(data, paper_template, ink_template)
    if not template.exists():
        raise FileNotFoundError(f"Template not found: {template}")

    output.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(template, output)

    doc = Document(str(output))
    fill_common_fields(doc, data)
    mark_checked_boxes(doc, data.get("selected_item_ids", []), label_map)
    fill_note_total(doc, data.get("total_with_tax"))
    doc.save(str(output))
    return output


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input_json", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "generated_forms" / "申請書_已填入.docx")
    parser.add_argument("--paper-template", type=Path, default=PAPER_TEMPLATE)
    parser.add_argument("--ink-template", type=Path, default=INK_TEMPLATE)
    args = parser.parse_args()

    data = json.loads(args.input_json.read_text(encoding="utf-8"))
    output = fill_application(data, args.paper_template, args.ink_template, args.out)
    print(output)


if __name__ == "__main__":
    main()
