def cell(row, index):
    return row.cells[index]


def roc_date(value: str | None = None) -> str:
    if value:
        try:
            parsed = date.fromisoformat(value[:10])
        except ValueError:
            parsed = date.today()
    else:
        parsed = date.today()
    return f"{parsed.year - 1911}年{parsed.month}月{parsed.day}日"


def format_run(run, font_size: float = 12.0) -> None:
    run.font.name = "標楷體"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "標楷體")
    run.font.size = Pt(font_size)
    apply_number_font(run)


def apply_number_font(run) -> None:
    if not any(char.isdigit() for char in run.text):
        return
    run._element.rPr.rFonts.set(qn("w:ascii"), NUMBER_FONT)
    run._element.rPr.rFonts.set(qn("w:hAnsi"), NUMBER_FONT)
    run._element.rPr.rFonts.set(qn("w:cs"), NUMBER_FONT)


def apply_number_font_to_doc(doc: Document) -> None:
    for paragraph in doc.paragraphs:
        for run in paragraph.runs:
            apply_number_font(run)
    for table in doc.tables:
        for row in table.rows:
            for target_cell in row.cells:
                for paragraph in target_cell.paragraphs:
                    for run in paragraph.runs:
                        apply_number_font(run)


def format_paragraph(paragraph, font_size: float = 12.0) -> None:
    for run in paragraph.runs:
        format_run(run, font_size)


def set_cell_text(
    target_cell, value: str, font_size: float = 12.0, alignment=None
) -> None:
    target_cell.text = value or ""
    for paragraph in target_cell.paragraphs:
        if alignment is not None:
            paragraph.alignment = alignment
        format_paragraph(paragraph, font_size)


def keep_cell_on_one_line(target_cell) -> None:
    tc_pr = target_cell._tc.get_or_add_tcPr()
    if tc_pr.find(qn("w:noWrap")) is None:
        tc_pr.append(OxmlElement("w:noWrap"))


def set_cell_width(target_cell, width: int) -> None:
    tc_w = target_cell._tc.get_or_add_tcPr().tcW
    if tc_w is not None:
        tc_w.w = width
        tc_w.type = "dxa"


def no_break(value: str) -> str:
    return str(value or "").replace(" ", "\u00a0")


def no_break_phone(value: str) -> str:
    return no_break(value)


def clone_run_properties(source_run, target_run) -> None:
    if source_run is None or source_run._r.rPr is None:
        return
    old_r_pr = target_run._r.rPr
    if old_r_pr is not None:
        target_run._r.remove(old_r_pr)
    target_run._r.insert(0, copy.deepcopy(source_run._r.rPr))


def add_text_like(paragraph, text: str, source_run=None):
    run = paragraph.add_run(str(text or ""))
    clone_run_properties(source_run, run)
    apply_number_font(run)
    return run


def set_paragraph_text_like(paragraph, text: str, source_run=None, bold: bool | None = None) -> None:
    if source_run is None and paragraph.runs:
        source_run = paragraph.runs[0]
    paragraph.clear()
    run = add_text_like(paragraph, text, source_run)
    if bold is not None:
        run.bold = bold


def add_formatted_run(paragraph, text: str, font_size: float = 12.0, underline: bool = False):
    run = paragraph.add_run(text)
    format_run(run, font_size)
    run.underline = underline
    return run


def replace_text_preserving_runs(
    doc: Document, replacements: dict[str, str], format_replacement: bool = False
) -> None:
    for paragraph in doc.paragraphs:
        replace_in_paragraph(paragraph, replacements, format_replacement=format_replacement)
    for table in doc.tables:
        for row in table.rows:
            for target_cell in row.cells:
                for paragraph in target_cell.paragraphs:
                    replace_in_paragraph(paragraph, replacements, format_replacement=format_replacement)


def replace_in_paragraph(
    paragraph, replacements: dict[str, str], format_replacement: bool = False
) -> None:
    if not paragraph.runs:
        return
    text = "".join(run.text for run in paragraph.runs)
    new_text = text
    for old, new in replacements.items():
        new_text = new_text.replace(old, new)
    if new_text == text:
        return
    paragraph.runs[0].text = new_text
    if format_replacement:
        format_run(paragraph.runs[0])
    for run in paragraph.runs[1:]:
        run.text = ""


def mark_checked_boxes(doc: Document, selected_item_ids: list[str], label_map: dict[str, str]) -> None:
    selected_labels = {label_map[item_id] for item_id in selected_item_ids if item_id in label_map}
    replacements = {}
    for label in selected_labels:
        replacements[f"□ {label}"] = f"■ {label}"
        replacements[f"□{label}"] = f"■{label}"
    replace_text_preserving_runs(doc, replacements)


def normalize_paper_item_labels(doc: Document) -> None:
    replace_text_preserving_runs(
        doc,
        {
            "17.表面強度蠟棒": "17.表面強度(蠟棒)",
            "18.表面強度IGT展色": "18.表面強度(IGT展色)",
        },
    )


def fill_common_fields(doc: Document, data: dict) -> None:
    table = doc.tables[0]
    customer = data.get("customer", {})
    sample = data.get("sample", {})
    application_date = data.get("application_date") or date.today().isoformat()

    set_cell_text(cell(table.rows[0], 2), customer.get("company_name", ""))
    keep_cell_on_one_line(cell(table.rows[0], 11))
    set_cell_text(cell(table.rows[0], 11), roc_date(application_date), 11, WD_ALIGN_PARAGRAPH.CENTER)
    set_cell_text(cell(table.rows[1], 2), customer.get("invoice_address") or customer.get("address", ""))
    set_cell_text(cell(table.rows[1], 11), customer.get("tax_id", ""), alignment=WD_ALIGN_PARAGRAPH.CENTER)
    set_cell_text(cell(table.rows[2], 2), customer.get("address", ""))
    set_cell_text(cell(table.rows[2], 11), customer.get("contact_name", ""), alignment=WD_ALIGN_PARAGRAPH.CENTER)
    set_cell_text(cell(table.rows[3], 2), customer.get("email", ""))
    set_cell_text(cell(table.rows[3], 11), customer.get("job_title", ""), alignment=WD_ALIGN_PARAGRAPH.CENTER)
    set_cell_width(cell(table.rows[4], 2), 2300)
    set_cell_width(cell(table.rows[4], 4), 1200)
    set_cell_width(cell(table.rows[4], 5), 1600)
    set_cell_width(cell(table.rows[4], 9), 1350)
    keep_cell_on_one_line(cell(table.rows[4], 2))
    set_cell_text(
        cell(table.rows[4], 2),
        no_break_phone(customer.get("phone", "")),
        11,
        WD_ALIGN_PARAGRAPH.CENTER,
    )
    set_cell_text(cell(table.rows[4], 5), customer.get("fax", ""), 11, WD_ALIGN_PARAGRAPH.CENTER)
    set_cell_text(cell(table.rows[4], 11), customer.get("mobile", ""), alignment=WD_ALIGN_PARAGRAPH.CENTER)

    fill_sample_cell(
        cell(table.rows[5], 1),
        sample.get("name", ""),
        sample.get("quantity", ""),
        sample.get("description", ""),
    )

    sample_return = sample.get("sample_return")
    report_delivery = sample.get("report_delivery")
    if sample_return:
        return_text = (
            f"剩餘測試件處理方式：{'■' if sample_return == '取回' else '□'}取回 "
            f"{'■' if sample_return == '不取回' else '□'}不取回"
        )
        set_cell_text(cell(table.rows[6], 1), return_text)
    if report_delivery:
        delivery_text = (
            f"正式紙本報告取件方式：{'■' if report_delivery == '自取' else '□'}自取 "
            f"{'■' if report_delivery == '郵寄' else '□'}郵寄"
        )
        set_cell_text(cell(table.rows[6], 7), delivery_text)

    case_type = sample.get("case_type", "一般件")
    replacements = {
        "□ 一般件": f"{'■' if case_type == '一般件' else '□'} 一般件",
        "□ 急件": f"{'■' if case_type == '急件' else '□'} 急件",
        "□ 特急件": f"{'■' if case_type == '特急件' else '□'} 特急件",
    }
    if sample.get("is_first_application") == "yes":
        attachments = set(sample.get("attachments", []))
        if "工廠登記證影本一份" in attachments:
            replacements["□工廠登記證影本一份"] = "■工廠登記證影本一份"
        if "公司執照影本一份" in attachments:
            replacements["□公司執照影本一份"] = "■公司執照影本一份"
        if "其他" in attachments or sample.get("attachment_other"):
            replacements["□其他_______"] = f"■其他 {sample.get('attachment_other', '')}"
            replacements["□其他________"] = f"■其他 {sample.get('attachment_other', '')}"
    replace_text_preserving_runs(doc, replacements)

    chinese_report_count = 1 + int(sample.get("extra_chinese_reports") or 0)
    english_report_count = int(sample.get("english_reports") or 0)
    replace_report_copy_lines(table, chinese_report_count, english_report_count)


def fill_sample_cell(target_cell, name: str, quantity: str, description: str) -> None:
    while len(target_cell.paragraphs) < 4:
        target_cell.add_paragraph()

    p0, p1, p2, p3 = target_cell.paragraphs[:4]
    template_run0 = p0.runs[0] if p0.runs else None
    template_run2 = p2.runs[0] if p2.runs else template_run0
    set_paragraph_text_like(
        p0,
        f"測試件名稱：                          測試件數量：{quantity or ''}",
        template_run0,
    )
    set_paragraph_text_like(p1, name or "", template_run0, bold=True)
    set_paragraph_text_like(p2, f"測試件狀態描述：{description or ''}", template_run2)
    set_paragraph_text_like(p3, "", template_run0)


def replace_report_copy_lines(table, chinese_report_count: int, english_report_count: int) -> None:
    chinese_paragraph = cell(table.rows[8], 1).paragraphs[0]
    chinese_paragraph.clear()
    add_formatted_run(chinese_paragraph, "■ 中文報告  ")
    add_formatted_run(chinese_paragraph, str(chinese_report_count), underline=True)
    add_formatted_run(chinese_paragraph, "  份")

    if english_report_count > 0:
        english_paragraph = cell(table.rows[8], 7).paragraphs[0]
        english_paragraph.clear()
        add_formatted_run(english_paragraph, "■ 英文報告  ")
        add_formatted_run(english_paragraph, str(english_report_count), underline=True)
        add_formatted_run(english_paragraph, "  份")


def fill_note_total(doc: Document, total: int | str | None) -> None:
    # The official application form keeps this amount blank for internal use.
    return


def choose_template(data: dict, paper_template: Path, ink_template: Path) -> tuple[Path, dict[str, str]]:
    service_type = data.get("service_type")
    if service_type == "paper":
        return paper_template, PAPER_ITEM_LABELS
    if service_type == "ink":
        return ink_template, INK_ITEM_LABELS

    selected = data.get("selected_item_ids", [])
    if selected and all(item_id.startswith("paper-") for item_id in selected):
        return paper_template, PAPER_ITEM_LABELS
    return ink_template, INK_ITEM_LABELS


def fill_application(data: dict, paper_template: Path, ink_template: Path, output: Path) -> Path:
    template, label_map = choose_template(data, paper_template, ink_template)
    if not template.exists():
        raise FileNotFoundError(f"Template not found: {template}")

    output.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(template, output)

    doc = Document(str(output))
    fill_common_fields(doc, data)
    if label_map is PAPER_ITEM_LABELS:
        normalize_paper_item_labels(doc)
    mark_checked_boxes(doc, data.get("selected_item_ids", []), label_map)
    fill_note_total(doc, data.get("total_with_tax"))
    doc.save(str(output))
    return output


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input_json", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "generated_forms" / "申請書_已填入.docx")
    parser.add_argument("--paper-template", type=Path, default=PAPER_TEMPLATE)
    parser.add_argument("--ink-template", type=Path, default=INK_TEMPLATE)
    args = parser.parse_args()

    data = json.loads(args.input_json.read_text(encoding="utf-8"))
    output = fill_application(data, args.paper_template, args.ink_template, args.out)
    print(output)


if __name__ == "__main__":
    main()
